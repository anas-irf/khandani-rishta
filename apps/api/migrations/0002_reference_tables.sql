CREATE TABLE countries (
    code        text PRIMARY KEY CHECK (code ~ '^[A-Z]{2}$'),   -- ISO 3166-1 alpha-2
    name        text NOT NULL,
    name_ur     text,
    dial_code   text,                                           -- '+92'
    sort_order  integer NOT NULL DEFAULT 1000,                  -- Pakistan first, then common diaspora countries
    is_active   boolean NOT NULL DEFAULT true
);

CREATE TABLE regions (                                          -- province, state or territory
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code  text NOT NULL REFERENCES countries (code),
    name          text NOT NULL,
    name_ur       text,
    UNIQUE (country_code, name)
);

CREATE TABLE cities (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    country_code  text NOT NULL REFERENCES countries (code),
    region_id     integer REFERENCES regions (id),
    name          text NOT NULL,
    name_ur       text,
    latitude      double precision,
    longitude     double precision,
    population    integer,
    is_major      boolean NOT NULL DEFAULT false                -- shown first in pickers
);
CREATE INDEX cities_country_region_idx ON cities (country_code, region_id);
CREATE INDEX cities_name_trgm_idx ON cities USING gin (name gin_trgm_ops);

CREATE TABLE religions (
    code        text PRIMARY KEY,
    name        text NOT NULL,
    name_ur     text,
    sort_order  integer NOT NULL DEFAULT 100,
    is_active   boolean NOT NULL DEFAULT true
);

CREATE TABLE sects (
    code           text PRIMARY KEY,
    religion_code  text NOT NULL REFERENCES religions (code),
    name           text NOT NULL,
    name_ur        text,
    sort_order     integer NOT NULL DEFAULT 100,
    is_active      boolean NOT NULL DEFAULT true
);
CREATE INDEX sects_religion_idx ON sects (religion_code);

-- Two levels only: a caste (parent_code IS NULL) and its sub-castes (parent_code = caste code).
CREATE TABLE castes (
    code         text PRIMARY KEY,
    parent_code  text REFERENCES castes (code),
    name         text NOT NULL,
    name_ur      text,
    aliases      text[] NOT NULL DEFAULT '{}',                  -- alternative spellings, used by search
    sort_order   integer NOT NULL DEFAULT 100,
    is_active    boolean NOT NULL DEFAULT true
);
CREATE INDEX castes_parent_idx ON castes (parent_code);
CREATE INDEX castes_name_trgm_idx ON castes USING gin (name gin_trgm_ops);

-- "Other" values typed by users. Moderators promote popular ones into `castes`.
CREATE TABLE caste_suggestions (
    id               uuid PRIMARY KEY DEFAULT uuidv7(),
    parent_code      text REFERENCES castes (code),             -- NULL: suggested as a top-level caste
    name             text NOT NULL CHECK (char_length(name) BETWEEN 2 AND 60),
    normalized_name  text NOT NULL,                             -- lowercase, single spaces
    usage_count      integer NOT NULL DEFAULT 1,
    status           text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'promoted', 'rejected')),
    promoted_code    text REFERENCES castes (code),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX caste_suggestions_unique_idx
    ON caste_suggestions (COALESCE(parent_code, ''), normalized_name);

