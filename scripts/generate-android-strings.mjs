#!/usr/bin/env node
// Turns the web app's English copy (apps/web/src/locales/en) into Android string resources, so
// both apps show the same words (specs/22 section 1). The admin console and the public pages are
// web only and are left out.
//
//   node scripts/generate-android-strings.mjs          writes the file
//   node scripts/generate-android-strings.mjs --check  fails when the committed file differs
//
// Naming: `<namespace>_<key path>` in lower case, for example `chat_composer_placeholder`.
// i18next placeholders `{{name}}` become `{name}`; the app fills them by name (ui/text/Text.kt).
// Plural keys (`_one`, `_other`) become <plurals>. Never edit the generated file by hand.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const localeDir = join(root, 'apps/web/src/locales/en')
const outFile = join(root, 'apps/android/app/src/main/res/values/copy.xml')
const check = process.argv.includes('--check')

const EXCLUDED = new Set(['admin', 'public'])
const PLURAL = /_(zero|one|two|few|many|other)$/

const strings = new Map() // name -> text
const plurals = new Map() // name -> Map(quantity -> text)
const origin = new Map() // name -> source key, to report collisions

function resourceName(parts) {
  return parts
    .join('_')
    .replace(/[^A-Za-z0-9_]+/g, '_')
    .replace(/_+/g, '_')
    .replace(/^_|_$/g, '')
    .toLowerCase()
}

function claim(name, source) {
  const previous = origin.get(name)
  if (previous && previous !== source) {
    throw new Error(`Two keys map to the resource name ${name}: ${previous} and ${source}`)
  }
  origin.set(name, source)
}

/**
 * A key is a plural form only when its base name has no plain key of its own and at least two
 * forms exist (`count_one` and `count_other`). `nikah_title_other` next to `nikah_title` is a
 * variant, not a plural.
 */
function isPluralKey(node, key) {
  const match = PLURAL.exec(key)
  if (!match) return null
  const base = key.slice(0, -match[0].length)
  if (Object.hasOwn(node, base)) return null
  const forms = Object.keys(node).filter(
    (k) =>
      k.startsWith(`${base}_`) && PLURAL.test(k) && k.slice(0, -PLURAL.exec(k)[0].length) === base,
  )
  return forms.length >= 2 ? match : null
}

function walk(namespace, node, path) {
  for (const [key, value] of Object.entries(node)) {
    if (value && typeof value === 'object') {
      walk(namespace, value, [...path, key])
      continue
    }
    if (typeof value !== 'string') continue
    const plural = isPluralKey(node, key)
    if (plural) {
      const base = key.slice(0, -plural[0].length)
      const name = resourceName([namespace, ...path, base])
      claim(name, `${namespace}:${[...path, base].join('.')} (plural)`)
      if (!plurals.has(name)) plurals.set(name, new Map())
      plurals.get(name).set(plural[1], value)
    } else {
      const name = resourceName([namespace, ...path, key])
      claim(name, `${namespace}:${[...path, key].join('.')}`)
      strings.set(name, value)
    }
  }
}

for (const file of readdirSync(localeDir).sort()) {
  if (!file.endsWith('.json')) continue
  const namespace = file.replace(/\.json$/, '')
  if (EXCLUDED.has(namespace)) continue
  walk(namespace, JSON.parse(readFileSync(join(localeDir, file), 'utf8')), [])
}

// A plural group needs at least "other"; a lone "one" falls back to it.
for (const forms of plurals.values()) {
  if (!forms.has('other')) forms.set('other', forms.get('one') ?? [...forms.values()][0])
}

function escapeXml(text) {
  let out = text
    .replace(/\{\{\s*([A-Za-z0-9_]+)\s*\}\}/g, '{$1}')
    .replace(/\\/g, '\\\\')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/'/g, "\\'")
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
  if (/^[@?]/.test(out)) out = `\\${out}`
  return out
}

const attrs = (text) => (text.includes('%') ? ' formatted="false"' : '')

const lines = [
  '<?xml version="1.0" encoding="utf-8"?>',
  '<!-- Generated by scripts/generate-android-strings.mjs from apps/web/src/locales/en.',
  '     Do not edit by hand: change the web copy and run `pnpm generate:android-strings`.',
  '     Placeholders such as {name} are filled by name with ui/text/Text.kt. -->',
  '<resources xmlns:tools="http://schemas.android.com/tools"',
  '    tools:ignore="UnusedResources,TypographyEllipsis,TypographyDashes,TypographyQuotes,PluralsCandidate,Typos">',
]
for (const name of [...strings.keys()].sort()) {
  const text = strings.get(name)
  lines.push(`    <string name="${name}"${attrs(text)}>${escapeXml(text)}</string>`)
}
for (const name of [...plurals.keys()].sort()) {
  lines.push(`    <plurals name="${name}">`)
  for (const quantity of ['zero', 'one', 'two', 'few', 'many', 'other']) {
    const text = plurals.get(name).get(quantity)
    if (text !== undefined)
      lines.push(`        <item quantity="${quantity}"${attrs(text)}>${escapeXml(text)}</item>`)
  }
  lines.push('    </plurals>')
}
lines.push('</resources>', '')
const output = lines.join('\n')

if (check) {
  let existing = ''
  try {
    existing = readFileSync(outFile, 'utf8')
  } catch {
    // Missing counts as out of date.
  }
  if (existing !== output) {
    console.error('The Android copy is out of date. Run `pnpm generate:android-strings`.')
    process.exit(1)
  }
  console.log(`Android copy is up to date (${strings.size} strings, ${plurals.size} plurals).`)
} else {
  writeFileSync(outFile, output)
  console.log(
    `Wrote ${strings.size} strings and ${plurals.size} plurals to apps/android/app/src/main/res/values/copy.xml`,
  )
}
